        id: g.id,
        kind: 'guide',
        platform: 'PDF',
        title: g.title,
        blurb: g.blurb + ' (not generated yet)',
        icon: g.icon,
        brand: 'solid',
        version: null,
        filename: null,
        url: null,
        size: 0,
