      blurb: 'Windows builds not found. Run npm run dist in desktop/, then re-sync.',
      icon: 'fa-windows',
      brand: 'brands',
      version: null,
      filename: null,
      url: null,
      size: 0,
      sizeLabel: '—',
      updatedAt: null,
      available: false,
