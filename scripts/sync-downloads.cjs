/**
 * Sync public download hub under /downloads/
 *
 * Copies the latest client apps + guides into stable public URLs so the
 * homepage "Downloads" section always points at current files after you rebuild.
 *
 * Also publishes the auto-update feeds:
 *   downloads/updates.json          — Android + portable + web + mac versions
 *   downloads/desktop/latest.yml    — electron-updater (Windows NSIS)
 *   downloads/desktop/latest-mac.yml— electron-updater (macOS)
 *   downloads/desktop/*.exe|*.dmg   — binaries for auto-update
 *
 * Sources (latest preferred):
 *   Android APK  → android-app/dist/RestroSuite-POS-*.apk
 *   Windows      → desktop/dist/ (portable + nsis + latest.yml)
 *   macOS        → desktop/dist/ (*-mac-*.dmg + latest-mac.yml)
 *   Product PDFs → docs/*.pdf
 *
 * Usage: node scripts/sync-downloads.cjs
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'downloads');
const DESKTOP_OUT = path.join(OUT, 'desktop');
const SITE = 'https://restrosuite.codearc.co.in';

function ensureDir(d) {
  fs.mkdirSync(d, { recursive: true });
}

function latestFile(dir, re) {
  if (!fs.existsSync(dir)) return null;
  const files = fs
    .readdirSync(dir)
    .filter((f) => re.test(f))
    .map((f) => {
      const p = path.join(dir, f);
      const st = fs.statSync(p);
      return { path: p, name: f, mtime: st.mtimeMs, size: st.size };
    })
    .sort((a, b) => b.mtime - a.mtime);
  return files[0] || null;
}

function copyStable(src, destName, destDir) {
  const dir = destDir || OUT;
  if (!src || !fs.existsSync(src.path || src)) return null;
  const from = src.path || src;
  ensureDir(dir);
  const to = path.join(dir, destName);
  fs.copyFileSync(from, to);
  const st = fs.statSync(to);
  const rel = path.relative(OUT, to).replace(/\\/g, '/');
  return {
    file: destName,
    url: '/downloads/' + rel,
    absoluteUrl: SITE + '/downloads/' + rel,
    size: st.size,
    sizeLabel: formatBytes(st.size),
    updatedAt: st.mtime.toISOString(),
  };
}

function formatBytes(n) {
  if (n < 1024) return n + ' B';
  if (n < 1024 * 1024) return (n / 1024).toFixed(0) + ' KB';
  if (n < 1024 * 1024 * 1024) return (n / (1024 * 1024)).toFixed(1) + ' MB';
  return (n / (1024 * 1024 * 1024)).toFixed(2) + ' GB';
}

function readJsonSafe(p) {
  try {
    return JSON.parse(fs.readFileSync(p, 'utf8'));
  } catch (_) {
    return {};
  }
}

function readTextSafe(p) {
  try {
    return fs.readFileSync(p, 'utf8');
  } catch (_) {
    return null;
  }
}

/** Parse versionCode / versionName from android-app/app/build.gradle */
function readAndroidVersions() {
  const gradle = readTextSafe(path.join(ROOT, 'android-app', 'app', 'build.gradle')) || '';
  const codeM = gradle.match(/versionCode\s+(\d+)/);
  const nameM = gradle.match(/versionName\s+"([^"]+)"/);
  return {
    versionCode: codeM ? parseInt(codeM[1], 10) : 0,
    versionName: nameM ? nameM[1] : null,
  };
}

/**
 * electron-builder writes latest.yml next to the NSIS artifact.
 * Copy the whole desktop feed folder so autoUpdater can find files by relative URL.
 */
function publishDesktopFeed(desktopDir, desktopPkg) {
  ensureDir(DESKTOP_OUT);
  const published = [];

  // Prefer latest.yml generated by electron-builder (required for electron-updater)
  const yml = latestFile(desktopDir, /^latest\.yml$/i);
  const nsis = latestFile(desktopDir, /RestroSuite-.*-x64\.exe$/i)
    || latestFile(desktopDir, /RestroSuite-.*Setup.*\.exe$/i);
  const blockmap = nsis
    ? latestFile(desktopDir, new RegExp(nsis.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\.blockmap$', 'i'))
    : latestFile(desktopDir, /\.exe\.blockmap$/i);
  const portable = latestFile(desktopDir, /portable\.exe$/i);

  if (yml) {
    const m = copyStable(yml, 'latest.yml', DESKTOP_OUT);
    if (m) published.push(m);
  }

  let nsisMeta = null;
  if (nsis) {
    // Keep original electron-builder filename so latest.yml paths resolve
    nsisMeta = copyStable(nsis, nsis.name, DESKTOP_OUT);
    if (nsisMeta) published.push(nsisMeta);
    // Also publish a stable public name for the downloads page
    copyStable(nsis, 'RestroSuite-Windows-Setup.exe', OUT);
  }

  if (blockmap) {
    const m = copyStable(blockmap, blockmap.name, DESKTOP_OUT);
    if (m) published.push(m);
  }

  let portableMeta = null;
  if (portable) {
    portableMeta = copyStable(portable, portable.name, DESKTOP_OUT);
    // Stable public name
    const stable = copyStable(portable, 'RestroSuite-Windows-Portable.exe', OUT);
    if (stable) portableMeta = Object.assign({}, portableMeta || {}, {
      stableUrl: stable.absoluteUrl,
      size: stable.size,
      sizeLabel: stable.sizeLabel,
      updatedAt: stable.updatedAt,
    });
  }

  // If latest.yml missing but we have an NSIS build, write a minimal feed so
  // clients can still discover version (electron-updater prefers real yml).
  if (!yml && nsis && desktopPkg.version) {
    const minimal =
      `version: ${desktopPkg.version}\n` +
      `files:\n` +
      `  - url: ${nsis.name}\n` +
      `    size: ${nsis.size}\n` +
      `path: ${nsis.name}\n` +
      `releaseDate: ${new Date().toISOString()}\n`;
    const ymlPath = path.join(DESKTOP_OUT, 'latest.yml');
    fs.writeFileSync(ymlPath, minimal);
    console.warn('Wrote minimal latest.yml (rebuild desktop with electron-builder for full sha512 feed)');
    published.push({ file: 'latest.yml', url: '/downloads/desktop/latest.yml' });
  }

  // macOS DMGs (built on macOS / GitHub Actions — may be absent on Windows dev machines)
  const macArm = latestFile(desktopDir, /RestroSuite-.*-mac-arm64\.dmg$/i)
    || latestFile(desktopDir, /.*-arm64\.dmg$/i);
  const macX64 = latestFile(desktopDir, /RestroSuite-.*-mac-x64\.dmg$/i)
    || latestFile(desktopDir, /.*-x64\.dmg$/i)
    || latestFile(desktopDir, /RestroSuite-.*-mac-intel\.dmg$/i);
  const macYml = latestFile(desktopDir, /^latest-mac\.yml$/i);
  const macZipArm = latestFile(desktopDir, /RestroSuite-.*-mac-arm64\.zip$/i);
  const macZipX64 = latestFile(desktopDir, /RestroSuite-.*-mac-x64\.zip$/i);

  let macArmMeta = null;
  let macX64Meta = null;
  if (macArm) {
    macArmMeta = copyStable(macArm, macArm.name, DESKTOP_OUT);
    copyStable(macArm, 'RestroSuite-Mac-AppleSilicon.dmg', OUT);
    if (macArmMeta) published.push(macArmMeta);
  }
  if (macX64) {
    macX64Meta = copyStable(macX64, macX64.name, DESKTOP_OUT);
    copyStable(macX64, 'RestroSuite-Mac-Intel.dmg', OUT);
    if (macX64Meta) published.push(macX64Meta);
  }
  if (macYml) {
    const m = copyStable(macYml, 'latest-mac.yml', DESKTOP_OUT);
    if (m) published.push(m);
  }
  if (macZipArm) {
    const m = copyStable(macZipArm, macZipArm.name, DESKTOP_OUT);
    if (m) published.push(m);
  }
  if (macZipX64) {
    const m = copyStable(macZipX64, macZipX64.name, DESKTOP_OUT);
    if (m) published.push(m);
  }

  return {
    published,
    nsisMeta,
    portableMeta,
    nsisName: nsis && nsis.name,
    portableName: portable && portable.name,
    macArmMeta,
    macX64Meta,
    macArmName: macArm && macArm.name,
    macX64Name: macX64 && macX64.name,
  };
}

